def encode_rle90(data: bytes) -> bytes:
    """Helper to encode byte stream into ARC/SQ RLE90 format."""
    out = bytearray()
    i = 0
    n = len(data)
    while i < n:
        b = data[i]
        # Count repeat length
        run_len = 1
        while i + run_len < n and data[i + run_len] == b and run_len < 255:
            run_len += 1

        if b == 0x90:
            # Literal 0x90 is encoded as 0x90 0x00
            for _ in range(run_len):
                out.extend([0x90, 0x00])
            i += run_len
        elif run_len >= 3:
            # Emit byte, then 0x90, then total count
            out.append(b)
            out.extend([0x90, run_len])
            i += run_len
        else:
            out.append(b)
            i += 1
    return bytes(out)


def build_synthetic_vault(
    entries: list[dict],
    xor_key: int = 32,
    flags: int = 0,
    corrupt_table_offset: bool = False,
    truncate_bytes: int = 0,
) -> bytes:
    """Helper to assemble a calibrated synthetic VLT1 binary archive."""
    magic = b"VLT1"
    entry_count = len(entries)

    # 1. Build blobs
    curr_blob_offset = 16  # starts immediately after 16-byte header
    blobs_data = bytearray()
    blob_records = []

    for entry in entries:
        raw_data = entry["data"]
        rle = entry.get("rle", False)
        is_xor = entry.get("xor", False)
        rec_id = entry["id"]

        processed = raw_data
        eflags = 0
        if rle:
            processed = encode_rle90(processed)
            eflags |= 0x01
        if is_xor:
            processed = bytes([b ^ ((xor_key + j) & 0xFF) for j, b in enumerate(processed)])
            eflags |= 0x02

        blob_header = struct.pack("<2sH", b"BL", rec_id)
        blob_full = blob_header + processed
        blob_offset = curr_blob_offset + len(blobs_data)
        blobs_data.extend(blob_full)

        blob_records.append({
            "id": rec_id,
            "type": entry.get("type", 1),
            "flags": eflags,
            "blob_offset": blob_offset,
            "stored_size": len(blob_full),
            "decomp_size": len(raw_data),
            "name": entry["name"],
        })

    # 2. Build names section
    names_offset = curr_blob_offset + len(blobs_data)
    names_data = bytearray()
    for br in blob_records:
        br["name_rel_offset"] = len(names_data)
        name_str = br["name"]
        raw_bytes = name_str.encode("utf-8")
        nlen_b = (len(raw_bytes) ^ xor_key) if (flags & 0x01) else len(raw_bytes)
        xored_name = bytes([b ^ ((xor_key + j) & 0xFF) for j, b in enumerate(raw_bytes)])
        names_data.append(nlen_b)
        names_data.extend(xored_name)

    # 3. Build index table
    table_offset = names_offset + len(names_data)
    table_data = bytearray()
    for br in blob_records:
        row = struct.pack(
            "<HBBIIHH",
            br["id"],
            br["type"],
            br["flags"],
            br["name_rel_offset"],
            br["blob_offset"],
            br["stored_size"],
            br["decomp_size"],
        )
        table_data.extend(row)

    # 4. Build Header
    act_tbl_off = table_offset if not corrupt_table_offset else 0x00FFFFFF
    header = struct.pack("<4sHBBII", magic, entry_count, xor_key, flags, act_tbl_off, names_offset)

    full_archive = header + blobs_data + names_data + table_data
    if truncate_bytes > 0:
        full_archive = full_archive[:-truncate_bytes]
    return bytes(full_archive)


class TestVaultParser(unittest.TestCase):
    def setUp(self):
        self.parser = VaultParser()

    def test_rle_decompression_primitives(self):
        # 1. Literal byte
        self.assertEqual(decompress_rle90(b"ABC", expected_len=3), b"ABC")

        # 2. RLE repetition: 'A' followed by 0x90, count=5 -> 5 'A's
        self.assertEqual(decompress_rle90(b"A\x90\x05", expected_len=5), b"AAAAA")

        # 3. Escaped 0x90: 0x90 followed by 0x00 -> literal 0x90
        self.assertEqual(decompress_rle90(b"\x90\x00", expected_len=1), b"\x90")

        # 4. Allocation cap enforcement
        with self.assertRaises(ValueError):
            decompress_rle90(b"A\x90\xFF", expected_len=255, max_len=10)

    def test_xor_deobfuscation_primitive(self):
        plain = b"Secret Plan"
        obfuscated = bytes(b ^ 0x42 for b in plain)
        self.assertEqual(xor_deobfuscate(obfuscated, 0x42), plain)
        self.assertEqual(xor_deobfuscate(plain, 0), plain)

    # --- Self-consistency tests ---

    def test_self_consistency_valid_synthetic_vault_archive(self):
        """[self-consistency] Valid VAULT archive generated by calibrated helper."""
        entries = [
            {"id": 101, "name": "readme.txt", "data": b"Welcome to VAULT test.", "rle": False, "xor": False, "type": 1},
            {"id": 102, "name": "rle_compressed.dat", "data": b"AAAAABBBBBCCCCCDDDDD", "rle": True, "xor": False, "type": 3},
            {"id": 103, "name": "xor_secret.txt", "data": b"Top secret operational directive.", "rle": False, "xor": True, "type": 1},
            {"id": 104, "name": "both.txt", "data": b"ZZZZZZZZZZ9999999999", "rle": True, "xor": True, "type": 1},
        ]
        data = build_synthetic_vault(entries)
        res = self.parser.parse("archive.vlt", BoundedBinaryReader(data))

        self.assertTrue(res.is_valid_header)
        self.assertEqual(len(res.recovered_records), 4)
        self.assertEqual(len(res.damages), 0)
        self.assertEqual(res.recovered_records[0].fields["text"], "Welcome to VAULT test.")
        self.assertEqual(res.recovered_records[1].fields["name"], "rle_compressed.dat")
        self.assertEqual(res.recovered_records[2].fields["text"], "Top secret operational directive.")
        self.assertEqual(res.recovered_records[3].fields["text"], "ZZZZZZZZZZ9999999999")

    def test_self_consistency_malformed_index_offset(self):
        """[self-consistency] Out-of-bounds index offset handling."""
        entries = [{"id": 1, "name": "a.txt", "data": b"Data", "rle": False}]
        data = build_synthetic_vault(entries, corrupt_table_offset=True)
        res = self.parser.parse("bad_index.vlt", BoundedBinaryReader(data))

        self.assertTrue(res.is_valid_header)
        self.assertEqual(len(res.recovered_records), 0)
        self.assertTrue(any(d.damage_type == DamageType.OOB_POINTER for d in res.damages))

    def test_self_consistency_truncated_archive(self):
        """[self-consistency] Truncated archive in index table."""
        entries = [{"id": 1, "name": "a.txt", "data": b"Data" * 20, "rle": False}]
        data = build_synthetic_vault(entries, truncate_bytes=10)
        res = self.parser.parse("trunc.vlt", BoundedBinaryReader(data))
        self.assertTrue(any(d.damage_type == DamageType.TRUNCATION for d in res.damages))

    # --- Independent fixtures ---

    def test_independent_handcrafted_vault_spec(self):
        """[independent] Hand-assembled VAULT archive binary using calibrated byte layout."""
        # Header (16B): b'VLT1', count=1, xor_key=32, flags=0, tbl_off=16+14+10=40, names_off=16+14=30
        blob_p = b"HELLO_VLT"
        blob = struct.pack("<2sH", b"BL", 777) + blob_p  # 4 + 9 = 13 bytes -> let's make it 14 bytes: 4 + 10
        blob_p = b"HELLO_VLT!"
        blob = struct.pack("<2sH", b"BL", 777) + blob_p  # 14 bytes

        # Name at 30: len=9, text='hello.txt' xored with (32 + j)
        raw_name = b"hello.txt"
        xored_name = bytes([b ^ ((32 + j) & 0xFF) for j, b in enumerate(raw_name)])
        name_sec = struct.pack("<B", len(raw_name)) + xored_name  # 1 + 9 = 10 bytes

        # Table at 40: 1 entry (16B)
        tbl_row = struct.pack("<HBBIIHH", 777, 1, 0, 0, 16, 14, 10)

        header = struct.pack("<4sHBBII", b"VLT1", 1, 32, 0, 40, 30)
        handcrafted = header + blob + name_sec + tbl_row

        res = self.parser.parse("independent_vault.vlt", BoundedBinaryReader(handcrafted))
        self.assertTrue(res.is_valid_header)
        self.assertEqual(len(res.recovered_records), 1)
        self.assertEqual(res.recovered_records[0].fields["id"], 777)
        self.assertEqual(res.recovered_records[0].fields["name"], "hello.txt")
        self.assertEqual(res.recovered_records[0].fields["text"], "HELLO_VLT!")
        self.assertEqual(len(res.damages), 0)


