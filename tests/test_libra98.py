"""Tests for LIBRA-98 defensive parser using clearly labelled synthetic fixtures."""

import unittest
import struct
import zlib
from src.formats.libra98 import Libra98Parser
from src.reader import BoundedBinaryReader
from src.models import RecordStatus, DamageType

def build_synthetic_libra98(
    records: list[tuple[int, int, int, int, str]],
    corrupt_header_crc: bool = False,
    corrupt_rec_crc_idx: int | None = None,
    truncate_bytes: int = 0,
) -> bytes:
    """Helper to build synthetic test fixtures for LIBRA-98."""
    magic = b"LIBRA98\x00"
    version = 0x0100
    flags = 0x0001
    header_size = 32
    rec_count = len(records)
    rec_size = 48

    header_pre = struct.pack("<8sHHIII", magic, version, flags, header_size, rec_count, rec_size)
    header_crc = zlib.crc32(header_pre) & 0xFFFFFFFF
    if corrupt_header_crc:
        header_crc ^= 0xDEADBEEF
    header = header_pre + struct.pack("<II", header_crc, 0)

    body = bytearray()
    for i, (rec_id, ts, status_f, val, label) in enumerate(records):
        label_bytes = label.encode("utf-8")[:30].ljust(30, b"\x00")
        rec_data = struct.pack("<IIHi30s", rec_id, ts, status_f, val, label_bytes)
        rec_crc = zlib.crc32(rec_data) & 0xFFFF
        if corrupt_rec_crc_idx == i:
            rec_crc ^= 0xBEEF
        body += rec_data + struct.pack("<HH", rec_crc, 0)

    data = header + body
    if truncate_bytes > 0:
        data = data[:-truncate_bytes]
    return bytes(data)

class TestLibra98Parser(unittest.TestCase):
    def setUp(self):
        self.parser = Libra98Parser()

    # --- Self-consistency tests (generated via project's build_synthetic_libra98 helper) ---

    def test_self_consistency_parse_valid_synthetic_file(self):
        """[self-consistency] Valid LIBRA-98 file generated by internal helper."""
        records = [
            (101, 1700000000, 1, 42, "Record Alpha"),
            (102, 1700000060, 2, 84, "Record Beta"),
        ]
        data = build_synthetic_libra98(records)
        reader = BoundedBinaryReader(data)
        res = self.parser.parse("valid_test.lib", reader)

        self.assertTrue(res.is_valid_header)
        self.assertEqual(len(res.recovered_records), 2)
        self.assertEqual(len(res.damages), 0)
        self.assertEqual(res.recovered_records[0].record_id, 101)
        self.assertEqual(res.recovered_records[0].status, RecordStatus.COMPLETE)
        self.assertEqual(res.recovered_records[0].fields["label"], "Record Alpha")
        self.assertEqual(res.recovered_records[1].fields["value"], 84)

    def test_self_consistency_parse_corrupted_header_checksum(self):
        """[self-consistency] Corrupted header checksum via synthetic helper."""
        records = [(1, 1000, 0, 10, "Test")]
        data = build_synthetic_libra98(records, corrupt_header_crc=True)
        res = self.parser.parse("corrupt_hdr.lib", BoundedBinaryReader(data))

        self.assertTrue(res.is_valid_header)
        self.assertEqual(len(res.recovered_records), 1)
        self.assertTrue(any(d.damage_type == DamageType.CHECKSUM_MISMATCH for d in res.damages))

    def test_self_consistency_parse_corrupted_record_checksum(self):
        """[self-consistency] Corrupted record checksum isolation via synthetic helper."""
        records = [
            (1, 1000, 0, 10, "Healthy"),
            (2, 2000, 0, 20, "Corrupt"),
        ]
        data = build_synthetic_libra98(records, corrupt_rec_crc_idx=1)
        res = self.parser.parse("corrupt_rec.lib", BoundedBinaryReader(data))

        self.assertEqual(len(res.recovered_records), 2)
        self.assertEqual(res.recovered_records[0].status, RecordStatus.COMPLETE)
        self.assertEqual(res.recovered_records[1].status, RecordStatus.CORRUPTED)
        self.assertTrue(any(d.damage_type == DamageType.CORRUPT_RECORD for d in res.damages))

    def test_self_consistency_truncated_file_recovers_intact_records(self):
        """[self-consistency] Truncated file recovers intact records via helper."""
        records = [
            (1, 1000, 0, 10, "Record 1"),
            (2, 2000, 0, 20, "Record 2"),
        ]
        data = build_synthetic_libra98(records, truncate_bytes=20)
        res = self.parser.parse("truncated.lib", BoundedBinaryReader(data))

        self.assertEqual(len(res.recovered_records), 1)
        self.assertEqual(res.recovered_records[0].record_id, 1)
        self.assertTrue(any(d.damage_type == DamageType.TRUNCATION for d in res.damages))

    def test_self_consistency_minimum_size_underflow(self):
        """[self-consistency] Minimum size truncation check."""
        data = b"LIBRA98"
        res = self.parser.parse("tiny.lib", BoundedBinaryReader(data))
        self.assertFalse(res.is_valid_header)
        self.assertEqual(len(res.recovered_records), 0)
        self.assertEqual(res.damages[0].damage_type, DamageType.TRUNCATION)

    # --- Independent fixtures (hand-assembled byte string according to provisional spec) ---

    def test_independent_handcrafted_libra98_spec(self):
        """
        [independent] Hand-assembled LIBRA-98 binary using explicit byte constants.
        Layout:
          Header (32B):
            Magic: b'LIBRA98\x00' (8B)
            Version: 0x0100 (2B LE) = \x00\x01
            Flags: 0x0001 (2B LE) = \x01\x00
            Header Size: 32 (4B LE) = \x20\x00\x00\x00
            Record Count: 1 (4B LE) = \x01\x00\x00\x00
            Record Size: 48 (4B LE) = \x30\x00\x00\x00
            Header CRC32 over bytes 0..23 = zlib.crc32(...)
            Reserved: 4 bytes zeros
          Record (48B):
            Rec ID: 999 = 0x000003E7 (4B LE)
            Timestamp: 1600000000 = 0x5F5E1000 (4B LE)
            Status: 1 (2B LE)
            Value: -500 (4B signed LE) = \x0c\xfe\xff\xff
            Label: b'HANDCRAFTED_SAMPLE' + 12 zeros (30B)
            Rec CRC16 over bytes 0..43
            Reserved: 2 bytes zeros
        """
        hdr_pre = b"LIBRA98\x00\x00\x01\x01\x00\x20\x00\x00\x00\x01\x00\x00\x00\x30\x00\x00\x00"
        hdr_crc = zlib.crc32(hdr_pre) & 0xFFFFFFFF
        header = hdr_pre + struct.pack("<II", hdr_crc, 0)
        self.assertEqual(len(header), 32)

        rec_label = b"HANDCRAFTED_SAMPLE" + b"\x00" * 12
        rec_data = struct.pack("<IIHi30s", 999, 1600000000, 1, -500, rec_label)
        self.assertEqual(len(rec_data), 44)
        rec_crc = zlib.crc32(rec_data) & 0xFFFF
        record = rec_data + struct.pack("<HH", rec_crc, 0)
        self.assertEqual(len(record), 48)

        handcrafted = header + record
        res = self.parser.parse("independent_libra.lib", BoundedBinaryReader(handcrafted))

        self.assertTrue(res.is_valid_header)
        self.assertEqual(len(res.recovered_records), 1)
        self.assertEqual(res.recovered_records[0].record_id, 999)
        self.assertEqual(res.recovered_records[0].fields["value"], -500)
        self.assertEqual(res.recovered_records[0].fields["label"], "HANDCRAFTED_SAMPLE")
        self.assertEqual(len(res.damages), 0)

if __name__ == "__main__":
    unittest.main()
