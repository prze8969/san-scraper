"""Tests for LIBRA-98 defensive parser using calibrated layouts from s01-s04."""

import unittest
import struct
from src.formats.libra98 import Libra98Parser
from src.reader import BoundedBinaryReader
from src.models import RecordStatus, DamageType


def encode_dos_date(year: int, month: int, day: int) -> int:
    return ((year - 1980) << 9) | (month << 5) | day


def encode_dos_time(hour: int, minute: int, sec: int) -> int:
    return (hour << 11) | (minute << 5) | (sec // 2)


def build_synthetic_libra98(
    records: list[dict],
    corrupt_trailer_crc: bool = False,
    corrupt_rec_crc_idx: int | None = None,
    truncate_bytes: int = 0,
    branch_id: int = 42,
    version: int = 2,
    data_offset: int = 16,
) -> bytes:
    """Helper to build calibrated test fixtures for LIBRA-98."""
    magic = b"LB98"
    count = len(records)
    created_d = encode_dos_date(1998, 5, 20)
    created_t = encode_dos_time(10, 30, 0)

    header = struct.pack("<4sHHHHHH", magic, version, count, created_d, created_t, data_offset, branch_id)
    if data_offset > 16:
        header += b"\x00" * (data_offset - 16)

    body = bytearray()
    for i, rec in enumerate(records):
        if isinstance(rec, tuple):
            # (id, timestamp, status_f, val, label)
            rec_id, ts, status_f, val, label = rec
            flags = status_f
            title = label.encode("cp437")
            author = "Unknown".encode("cp437")
            raw_year = 1990 - 1500
            price_cents = 1000
            copies = 1
            isbn = b"1234567890"
            due_d = 0
        else:
            flags = rec.get("flags", 0)
            rec_id = rec.get("id", 100 + i)
            title = rec.get("title", f"Book {i}").encode("cp437")
            author = rec.get("author", f"Author {i}").encode("cp437")
            raw_year = rec.get("year", 1990) - 1500
            price_cents = rec.get("price_cents", 1299)
            copies = rec.get("copies", 1)
            isbn = rec.get("isbn", "1234567890").encode("ascii")[:10].ljust(10, b" ")
            due_d = rec.get("due_date_raw", 0)

        # payload starting from flags through due_date
        rec_content = struct.pack(
            f"<B I B{len(title)}s B{len(author)}s H H B 10s H",
            flags,
            rec_id,
            len(title),
            title,
            len(author),
            author,
            raw_year,
            price_cents,
            copies,
            isbn,
            due_d,
        )
        rec_cksum = sum(rec_content) % 256
        if corrupt_rec_crc_idx == i:
            rec_cksum = (rec_cksum + 1) % 256

        # frame: 0xA5, length, content, checksum
        frame_len = len(rec_content) + 1  # includes checksum
        frame = struct.pack("<BB", 0xA5, frame_len) + rec_content + struct.pack("<B", rec_cksum)
        body += frame

    # Trailer: b'END!' + file_checksum (sum of all bytes before END! % 65536)
    pre_trailer = header + bytes(body)
    file_cksum = sum(pre_trailer) % 65536
    if corrupt_trailer_crc:
        file_cksum = (file_cksum + 1) % 65536

    trailer = b"END!" + struct.pack("<H", file_cksum)
    data = pre_trailer + trailer

    if truncate_bytes > 0:
        data = data[:-truncate_bytes]
    return bytes(data)


class TestLibra98Parser(unittest.TestCase):
    def setUp(self):
        self.parser = Libra98Parser()

    # --- Self-consistency tests ---

    def test_self_consistency_parse_valid_synthetic_file(self):
        """[self-consistency] Valid LIBRA-98 file generated by internal helper."""
        records = [
            {"id": 101, "title": "Record Alpha", "author": "John Doe", "year": 1995, "price_cents": 1500, "copies": 3, "isbn": "0123456789"},
            {"id": 102, "title": "Record Beta", "author": "Jane Smith", "year": 1999, "price_cents": 2500, "copies": 1, "isbn": "9876543210"},
        ]
        data = build_synthetic_libra98(records)
        reader = BoundedBinaryReader(data)
        res = self.parser.parse("valid_test.lib", reader)

        self.assertTrue(res.is_valid_header)
        self.assertEqual(len(res.recovered_records), 2)
        self.assertEqual(len(res.damages), 0)
        self.assertEqual(res.recovered_records[0].fields["id"], 101)
        self.assertEqual(res.recovered_records[0].status, RecordStatus.COMPLETE)
        self.assertEqual(res.recovered_records[0].fields["title"], "Record Alpha")
        self.assertEqual(res.recovered_records[1].fields["price_cents"], 2500)

    def test_self_consistency_parse_corrupted_header_checksum(self):
        """[self-consistency] Corrupted trailer checksum via synthetic helper."""
        records = [{"id": 1, "title": "Test", "author": "Author", "year": 1990}]
        data = build_synthetic_libra98(records, corrupt_trailer_crc=True)
        res = self.parser.parse("corrupt_trailer.lib", BoundedBinaryReader(data))

        self.assertTrue(res.is_valid_header)
        self.assertEqual(len(res.recovered_records), 1)
        self.assertTrue(any(d.damage_type == DamageType.CHECKSUM_MISMATCH for d in res.damages))

    def test_self_consistency_parse_corrupted_record_checksum(self):
        """[self-consistency] Corrupted record checksum isolation via synthetic helper."""
        records = [
            {"id": 1, "title": "Healthy", "author": "Good", "year": 1990},
            {"id": 2, "title": "Corrupt", "author": "Bad", "year": 1991},
        ]
        data = build_synthetic_libra98(records, corrupt_rec_crc_idx=1)
        res = self.parser.parse("corrupt_rec.lib", BoundedBinaryReader(data))

        self.assertEqual(len(res.recovered_records), 2)
        self.assertEqual(res.recovered_records[0].status, RecordStatus.COMPLETE)
        self.assertEqual(res.recovered_records[1].status, RecordStatus.CORRUPTED)
        self.assertTrue(any(d.damage_type == DamageType.CORRUPT_RECORD for d in res.damages))

    def test_self_consistency_truncated_file_recovers_intact_records(self):
        """[self-consistency] Truncated file recovers intact records via helper."""
        records = [
            {"id": 1, "title": "Record 1", "author": "A1", "year": 1990},
            {"id": 2, "title": "Record 2", "author": "A2", "year": 1992},
        ]
        # Truncate second record
        data = build_synthetic_libra98(records, truncate_bytes=20)
        res = self.parser.parse("truncated.lib", BoundedBinaryReader(data))

        self.assertEqual(len(res.recovered_records), 1)
        self.assertEqual(res.recovered_records[0].fields["id"], 1)
        self.assertTrue(any(d.damage_type == DamageType.TRUNCATION for d in res.damages))

    def test_self_consistency_minimum_size_underflow(self):
        """[self-consistency] Minimum size truncation check."""
        data = b"LB98"
        res = self.parser.parse("tiny.lib", BoundedBinaryReader(data))
        self.assertFalse(res.is_valid_header)
        self.assertEqual(len(res.recovered_records), 0)
        self.assertEqual(res.damages[0].damage_type, DamageType.TRUNCATION)

    # --- Independent fixtures ---

    def test_independent_handcrafted_libra98_spec(self):
        """[independent] Hand-assembled LIBRA-98 binary using calibrated byte layout."""
        # Header (16B): magic b'LB98', ver 2, count 1, date 0x24a5, time 0x5460, data_offset 16, branch 7
        hdr = struct.pack("<4sHHHHHH", b"LB98", 2, 1, 0x24A5, 0x5460, 16, 7)
        # Record: sync 0xA5, len N, flags 0, id 999, title 'TestBook', author 'TestAuth', raw_year 490, price 999, copies 2, isbn '1234567890', due 0
        title = b"TestBook"
        author = b"TestAuth"
        rec_content = struct.pack(
            f"<B I B{len(title)}s B{len(author)}s H H B 10s H",
            0,
            999,
            len(title),
            title,
            len(author),
            author,
            490,
            999,
            2,
            b"1234567890",
            0,
        )
        rec_cksum = sum(rec_content) % 256
        rec_frame = struct.pack("<BB", 0xA5, len(rec_content) + 1) + rec_content + struct.pack("<B", rec_cksum)
        pre_trailer = hdr + rec_frame
        file_cksum = sum(pre_trailer) % 65536
        trailer = b"END!" + struct.pack("<H", file_cksum)
        handcrafted = pre_trailer + trailer

        res = self.parser.parse("independent_libra.lib", BoundedBinaryReader(handcrafted))

        self.assertTrue(res.is_valid_header)
        self.assertEqual(len(res.recovered_records), 1)
        self.assertEqual(res.recovered_records[0].fields["id"], 999)
        self.assertEqual(res.recovered_records[0].fields["year"], 1990)
        self.assertEqual(res.recovered_records[0].fields["title"], "TestBook")
        self.assertEqual(len(res.damages), 0)


if __name__ == "__main__":
    unittest.main()
