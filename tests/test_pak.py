"""Tests for Quake PAK archive defensive parser."""

import unittest
import struct
from src.formats.pak import PakParser
from src.reader import BoundedBinaryReader
from src.models import RecordStatus, DamageType

def build_synthetic_pak(
    files: list[tuple[str, bytes]],  # (filename, content)
    dir_offset_override: int | None = None,
    dir_len_override: int | None = None,
    directory_at_start: bool = False,
    truncate_bytes: int = 0,
) -> bytes:
    """Helper to assemble a synthetic id Software Quake PAK file."""
    magic = b"PACK"

    # Pack files payload
    payloads = bytearray()
    file_metadata = []

    # If directory is placed after header before payloads:
    dir_size = len(files) * 64
    if directory_at_start:
        base_payload_offset = 12 + dir_size
    else:
        base_payload_offset = 12

    for fname, content in files:
        f_off = base_payload_offset + len(payloads)
        f_sz = len(content)
        payloads.extend(content)
        file_metadata.append((fname, f_off, f_sz))

    # Assemble directory table
    directory_bytes = bytearray()
    for fname, f_off, f_sz in file_metadata:
        name_bytes = fname.encode("latin-1")[:56].ljust(56, b"\x00")
        entry = struct.pack("<56sII", name_bytes, f_off, f_sz)
        directory_bytes.extend(entry)

    if directory_at_start:
        dir_off = 12
        full_data = bytearray(struct.pack("<4sII", magic, dir_off, dir_size))
        full_data.extend(directory_bytes)
        full_data.extend(payloads)
    else:
        dir_off = 12 + len(payloads)
        actual_dir_off = dir_off if dir_offset_override is None else dir_offset_override
        actual_dir_len = len(directory_bytes) if dir_len_override is None else dir_len_override
        header = struct.pack("<4sII", magic, actual_dir_off, actual_dir_len)
        full_data = bytearray(header + payloads + directory_bytes)

    if truncate_bytes > 0:
        full_data = full_data[:-truncate_bytes]
    return bytes(full_data)

class TestPakParser(unittest.TestCase):
    def setUp(self):
        self.parser = PakParser()

    # --- Self-consistency tests (generated via project's build_synthetic_pak helper) ---

    def test_self_consistency_valid_synthetic_pak(self):
        """[self-consistency] Valid PAK generated by internal helper."""
        files = [
            ("progs.dat", b"\x01\x02\x03\x04" * 10),
            ("maps/e1m1.bsp", b"BSP_DATA_CHUNKS"),
            ("sound/player/jump.wav", b"RIFF_FAKE_WAV"),
        ]
        data = build_synthetic_pak(files)
        res = self.parser.parse("pak0.pak", BoundedBinaryReader(data))

        self.assertTrue(res.is_valid_header)
        self.assertEqual(len(res.recovered_records), 3)
        self.assertEqual(res.recovered_records[0].fields["name"], "progs.dat")
        self.assertEqual(res.recovered_records[1].fields["name"], "maps/e1m1.bsp")
        self.assertEqual(res.recovered_records[2].fields["name"], "sound/player/jump.wav")
        self.assertEqual(len(res.damages), 0)

    def test_self_consistency_directory_located_before_payloads(self):
        """[self-consistency] PAK with directory placed ahead of payloads."""
        files = [("config.cfg", b"bind mouse1 +attack")]
        data = build_synthetic_pak(files, directory_at_start=True)
        res = self.parser.parse("dir_first.pak", BoundedBinaryReader(data))

        self.assertTrue(res.is_valid_header)
        self.assertEqual(len(res.recovered_records), 1)
        self.assertEqual(res.recovered_records[0].fields["name"], "config.cfg")

    def test_self_consistency_path_traversal_sanitization(self):
        """[self-consistency] Tests path sanitization using synthetic helper."""
        files = [
            ("../../etc/passwd", b"evil"),
            ("C:\\Windows\\System32\\cmd.exe", b"calc"),
            ("./scripts/test.txt", b"ok"),
            ("NUL", b"device_test"),
            ("CON.txt", b"con_test"),
        ]
        data = build_synthetic_pak(files)
        res = self.parser.parse("traversal.pak", BoundedBinaryReader(data))

        self.assertEqual(res.recovered_records[0].fields["name"], "etc/passwd")
        self.assertTrue(any("Sanitized unsafe directory traversal" in e for e in res.recovered_records[0].errors))
        self.assertEqual(res.recovered_records[1].fields["name"], "Windows/System32/cmd.exe")
        self.assertEqual(res.recovered_records[2].fields["name"], "scripts/test.txt")
        self.assertEqual(res.recovered_records[3].fields["name"], "safe_NUL")
        self.assertEqual(res.recovered_records[4].fields["name"], "safe_CON.txt")

    def test_self_consistency_invalid_directory_length(self):
        """[self-consistency] Non-64-byte aligned directory length."""
        files = [("a.txt", b"123")]
        data = build_synthetic_pak(files, dir_len_override=70)
        res = self.parser.parse("bad_dirlen.pak", BoundedBinaryReader(data))
        self.assertTrue(any(d.damage_type == DamageType.INVALID_HEADER for d in res.damages))

    def test_self_consistency_entry_offset_exceeds_bounds(self):
        """[self-consistency] Directory entry offset out of file bounds."""
        files = [
            ("valid.txt", b"Good data"),
            ("corrupt.txt", b"Corrupt payload bounds"),
        ]
        data = bytearray(build_synthetic_pak(files))
        dir_off = struct.unpack("<I", data[4:8])[0]
        struct.pack_into("<I", data, dir_off + 64 + 56, 0x00FFFFFF)

        res = self.parser.parse("corrupt_entry.pak", BoundedBinaryReader(bytes(data)))
        self.assertEqual(len(res.recovered_records), 2)
        self.assertEqual(res.recovered_records[0].status, RecordStatus.COMPLETE)
        self.assertEqual(res.recovered_records[1].status, RecordStatus.UNRECOVERABLE)
        self.assertTrue(any(d.damage_type == DamageType.MALFORMED_OFFSET for d in res.damages))

    def test_self_consistency_truncated_directory(self):
        """[self-consistency] Truncated directory table."""
        files = [("a.txt", b"123"), ("b.txt", b"456")]
        data = build_synthetic_pak(files, truncate_bytes=30)
        res = self.parser.parse("trunc.pak", BoundedBinaryReader(data))
        self.assertTrue(any(d.damage_type == DamageType.TRUNCATION for d in res.damages))

    # --- Independent fixtures (hand-assembled byte strings from Quake PAK spec, no writer used) ---

    def test_independent_handcrafted_pak_spec(self):
        """
        [independent] Hand-assembled Quake PAK binary according to id Software Quake spec.
        Source: id Software Quake source code (quakedef.h, dpackheader_t, dpackfile_t).
        Header:
          Magic: 'PACK' (4B) = b'PACK'
          Dir Offset: 12 + 10 = 22 = 0x00000016 (4B uint32 LE)
          Dir Length: 64 = 0x00000040 (4B uint32 LE)
        Payload (offset 12..22):
          10 bytes: b'HELLOQUAKE'
        Directory Entry (offset 22..86, 64B):
          Name (56B): b'test.txt\x00' padded with nulls
          Offset (4B): 12 = 0x0000000C (4B uint32 LE)
          Size (4B): 10 = 0x0000000A (4B uint32 LE)
        """
        handcrafted = (
            b"PACK"                                     # Magic
            + b"\x16\x00\x00\x00"                       # Dir offset: 22
            + b"\x40\x00\x00\x00"                       # Dir length: 64 (1 entry)
            + b"HELLOQUAKE"                             # File payload (10 bytes at offset 12)
            + b"test.txt" + b"\x00" * (56 - len(b"test.txt")) # Entry name (56B)
            + b"\x0c\x00\x00\x00"                       # File offset: 12
            + b"\x0a\x00\x00\x00"                       # File size: 10
        )
        self.assertEqual(len(handcrafted), 12 + 10 + 64)
        res = self.parser.parse("independent_quake.pak", BoundedBinaryReader(handcrafted))

        self.assertTrue(res.is_valid_header)
        self.assertEqual(len(res.recovered_records), 1)
        self.assertEqual(res.recovered_records[0].fields["name"], "test.txt")
        self.assertEqual(res.recovered_records[0].fields["offset"], 12)
        self.assertEqual(res.recovered_records[0].fields["size"], 10)
        self.assertEqual(len(res.damages), 0)

    def test_independent_handcrafted_traversal_and_duplicate(self):
        """
        [independent] Hand-assembled PAK with duplicate names and directory traversal payloads.
        Source: id Software Quake PAK layout & security requirements.
        """
        # Header: dir at offset 12, dir_len 128 (2 entries of 64 bytes)
        entry1_name = b"../../secret.cfg" + b"\x00" * (56 - len(b"../../secret.cfg"))
        entry1 = entry1_name + b"\x00\x00\x00\x00" + b"\x00\x00\x00\x00" # offset 0, size 0
        entry2_name = b"secret.cfg" + b"\x00" * (56 - len(b"secret.cfg"))
        entry2 = entry2_name + b"\x00\x00\x00\x00" + b"\x00\x00\x00\x00" # duplicate after sanitization
        handcrafted = (
            b"PACK"
            + b"\x0c\x00\x00\x00"  # dir offset = 12
            + b"\x80\x00\x00\x00"  # dir len = 128
            + entry1
            + entry2
        )
        res = self.parser.parse("independent_traversal.pak", BoundedBinaryReader(handcrafted))
        self.assertEqual(len(res.recovered_records), 2)
        # Entry 1 was sanitized
        self.assertEqual(res.recovered_records[0].fields["name"], "secret.cfg")
        self.assertTrue(any("Sanitized unsafe directory traversal" in e for e in res.recovered_records[0].errors))
        # Entry 2 collides with entry 1 after sanitization
        self.assertEqual(res.recovered_records[1].fields["name"], "secret.cfg")
        self.assertTrue(any("Duplicate entry name" in e for e in res.recovered_records[1].errors))

    def test_independent_handcrafted_overlapping_ranges(self):
        """
        [independent] Hand-assembled PAK where payload overlaps directory table.
        Source: id Software Quake archive safety checks.
        """
        # Header: dir at offset 12, dir len 64.
        # Entry declared at offset 10 with size 20 (overlaps header and directory!)
        entry_name = b"overlap.dat" + b"\x00" * (56 - len(b"overlap.dat"))
        entry = (
            entry_name
            + b"\x0a\x00\x00\x00"  # offset 10
            + b"\x14\x00\x00\x00"  # size 20 (10 to 30 overlaps directory at 12..76)
        )
        handcrafted = b"PACK\x0c\x00\x00\x00\x40\x00\x00\x00" + entry
        res = self.parser.parse("independent_overlap.pak", BoundedBinaryReader(handcrafted))
        self.assertEqual(len(res.recovered_records), 1)
        self.assertTrue(any("Payload overlaps directory table" in e for e in res.recovered_records[0].errors))

if __name__ == "__main__":
    unittest.main()

