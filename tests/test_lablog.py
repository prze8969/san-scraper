"""Tests for LABLOG defensive parser using synthetic fixtures."""

import unittest
import struct
import zlib
from src.formats.lablog import LablogParser
from src.reader import BoundedBinaryReader
from src.models import RecordStatus, DamageType

def build_synthetic_lablog(
    blocks: list[tuple[int, int, int, int, bytes]],  # (seq_id, blk_type, flags, ts, payload)
    corrupt_hdr_crc: bool = False,
    corrupt_block_crc_idx: int | None = None,
    insert_garbage_before_idx: tuple[int, bytes] | None = None,
    truncate_bytes: int = 0,
) -> bytes:
    """Helper to build synthetic test fixtures for LABLOG."""
    magic = b"LABLOG\x01\x00"
    version = 1
    block_count = len(blocks)
    hdr_pre = struct.pack("<8sHH", magic, version, block_count)
    hdr_crc = zlib.crc32(hdr_pre) & 0xFFFFFFFF
    if corrupt_hdr_crc:
        hdr_crc ^= 0xDEADBEEF
    created_ts = 1710000000
    header = hdr_pre + struct.pack("<IQ", hdr_crc, created_ts)

    body = bytearray()
    for i, (seq_id, blk_type, flags, ts, payload) in enumerate(blocks):
        if insert_garbage_before_idx and insert_garbage_before_idx[0] == i:
            body += insert_garbage_before_idx[1]

        sync = b"BLOK"
        payload_len = len(payload)
        payload_crc = zlib.crc32(payload) & 0xFFFFFFFF
        if corrupt_block_crc_idx == i:
            payload_crc ^= 0xBEEF

        blk_hdr = struct.pack("<4sIHHIII", sync, seq_id, blk_type, flags, payload_len, payload_crc, ts)
        body += blk_hdr + payload

    data = header + body
    if truncate_bytes > 0:
        data = data[:-truncate_bytes]
    return bytes(data)

class TestLablogParser(unittest.TestCase):
    def setUp(self):
        self.parser = LablogParser()

    # --- Self-consistency tests (generated via project's build_synthetic_lablog helper) ---

    def test_self_consistency_parse_valid_synthetic_lablog(self):
        """[self-consistency] Valid LABLOG file generated by internal helper."""
        blocks = [
            (0, 1, 0, 1710000010, b"Experiment initialized."),
            (1, 2, 0, 1710000020, b"Temperature fluctuation noted."),
            (2, 1, 0, 1710000030, b"Process completed safely."),
        ]
        data = build_synthetic_lablog(blocks)
        res = self.parser.parse("valid_log.lab", BoundedBinaryReader(data))

        self.assertTrue(res.is_valid_header)
        self.assertEqual(len(res.recovered_records), 3)
        self.assertEqual(len(res.damages), 0)
        self.assertEqual(res.recovered_records[0].fields["payload_text"], "Experiment initialized.")
        self.assertEqual(res.recovered_records[1].status, RecordStatus.COMPLETE)

    def test_self_consistency_corrupted_block_checksum_isolation(self):
        """[self-consistency] Checksum isolation via synthetic helper."""
        blocks = [
            (0, 1, 0, 100, b"Healthy Block 0"),
            (1, 1, 0, 101, b"Corrupted Block 1"),
            (2, 1, 0, 102, b"Healthy Block 2"),
        ]
        data = build_synthetic_lablog(blocks, corrupt_block_crc_idx=1)
        res = self.parser.parse("corrupt_blk.lab", BoundedBinaryReader(data))

        self.assertEqual(len(res.recovered_records), 3)
        self.assertEqual(res.recovered_records[0].status, RecordStatus.COMPLETE)
        self.assertEqual(res.recovered_records[1].status, RecordStatus.CORRUPTED)
        self.assertEqual(res.recovered_records[2].status, RecordStatus.COMPLETE)
        self.assertEqual(res.recovered_records[2].fields["payload_text"], "Healthy Block 2")
        self.assertTrue(any(d.damage_type == DamageType.CHECKSUM_MISMATCH for d in res.damages))

    def test_self_consistency_block_resynchronization(self):
        """[self-consistency] Sync marker scanning across garbage via helper."""
        blocks = [
            (0, 1, 0, 100, b"Block Alpha"),
            (1, 1, 0, 101, b"Block Beta"),
        ]
        garbage = b"\xFF\xFE\xDD\xCC\xBB\xAA\x00\x11"
        data = build_synthetic_lablog(blocks, insert_garbage_before_idx=(1, garbage))
        res = self.parser.parse("resync.lab", BoundedBinaryReader(data))

        self.assertEqual(len(res.recovered_records), 2)
        self.assertEqual(res.recovered_records[0].fields["payload_text"], "Block Alpha")
        self.assertEqual(res.recovered_records[1].fields["payload_text"], "Block Beta")
        self.assertTrue(any(d.damage_type == DamageType.CORRUPT_RECORD for d in res.damages))

    def test_self_consistency_truncated_block_recovery(self):
        """[self-consistency] Partial recovery on block payload truncation."""
        blocks = [
            (0, 1, 0, 100, b"Block Full"),
            (1, 1, 0, 101, b"Block that gets truncated midway"),
        ]
        data = build_synthetic_lablog(blocks, truncate_bytes=10)
        res = self.parser.parse("trunc.lab", BoundedBinaryReader(data))

        self.assertEqual(len(res.recovered_records), 2)
        self.assertEqual(res.recovered_records[0].status, RecordStatus.COMPLETE)
        self.assertEqual(res.recovered_records[1].status, RecordStatus.PARTIAL)
        self.assertTrue(any(d.damage_type == DamageType.TRUNCATION for d in res.damages))

    # --- Independent fixtures (hand-assembled byte string according to provisional spec) ---

    def test_independent_handcrafted_lablog_spec(self):
        """
        [independent] Hand-assembled LABLOG binary using explicit byte definitions.
        Layout:
          Header (24B):
            Magic: b'LABLOG\x01\x00' (8B)
            Version: 1 (2B LE) = \x01\x00
            Block Count: 1 (2B LE) = \x01\x00
            Header CRC32 over bytes 0..11
            Created TS: 1700000000 (8B LE)
          Block Frame (24B + N):
            Sync: b'BLOK' (4B)
            Seq ID: 50 (4B LE)
            Block Type: 1 (2B LE)
            Flags: 0 (2B LE)
            Payload Length N: 16 (4B LE)
            Payload CRC32 over payload bytes
            Timestamp: 1700000010 (4B LE)
            Payload: b'INDEPENDENT_DATA' (16B)
        """
        hdr_pre = b"LABLOG\x01\x00\x01\x00\x01\x00"
        hdr_crc = zlib.crc32(hdr_pre) & 0xFFFFFFFF
        header = hdr_pre + struct.pack("<IQ", hdr_crc, 1700000000)
        self.assertEqual(len(header), 24)

        payload = b"INDEPENDENT_DATA"
        payload_crc = zlib.crc32(payload) & 0xFFFFFFFF
        blk_hdr = struct.pack("<4sIHHIII", b"BLOK", 50, 1, 0, len(payload), payload_crc, 1700000010)
        handcrafted = header + blk_hdr + payload

        res = self.parser.parse("independent_log.lab", BoundedBinaryReader(handcrafted))
        self.assertTrue(res.is_valid_header)
        self.assertEqual(len(res.recovered_records), 1)
        self.assertEqual(res.recovered_records[0].record_id, 50)
        self.assertEqual(res.recovered_records[0].fields["payload_text"], "INDEPENDENT_DATA")
        self.assertEqual(res.recovered_records[0].status, RecordStatus.COMPLETE)
        self.assertEqual(len(res.damages), 0)

if __name__ == "__main__":
    unittest.main()
