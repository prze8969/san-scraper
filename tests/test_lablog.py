"""Tests for LABLOG defensive parser using calibrated LLOG layout."""

import unittest
import struct
import datetime
from src.formats.lablog import LablogParser, crc16_ccitt
from src.reader import BoundedBinaryReader
from src.models import RecordStatus, DamageType


def build_synthetic_lablog(
    blocks: list[dict],
    instrument: str = "SYNTHETIC-LOG",
    sample_interval_ms: int = 500,
    corrupt_hdr_crc: bool = False,
    corrupt_block_crc_idx: int | None = None,
    truncate_bytes: int = 0,
) -> bytes:
    """Helper to build calibrated synthetic test fixtures for LABLOG."""
    magic = b"LLOG"
    version = 1
    num_ch = 2
    interval_units = sample_interval_ms // 10

    # start_time 1992-10-11 05:07:43 UTC = 87628063 sec since 1990
    start_sec = 87628063
    decl_blocks = len(blocks) + 1  # includes channel block

    instr_bytes = instrument.encode("ascii").ljust(16, b"\x00")[:16]
    pre_hdr = struct.pack("<4sBBH16sIH", magic, version, num_ch, interval_units, instr_bytes, start_sec, decl_blocks)
    hdr_crc = crc16_ccitt(pre_hdr)
    if corrupt_hdr_crc:
        hdr_crc ^= 0xDEAD
    header = pre_hdr + struct.pack("<H", hdr_crc)

    # Channel block:
    # 2 channels: mV (scale 0.5, offset 100.0), ppm (scale 0.5, offset 20.5)
    ch_payload = struct.pack("<4sff4sff", b"mV\x00\x00", 0.5, 100.0, b"ppm\x00", 0.5, 20.5)
    ch_hdr = struct.pack("<BBH", 0xB1, 3, len(ch_payload))
    ch_crc = crc16_ccitt(struct.pack("<BH", 3, len(ch_payload)) + ch_payload)
    ch_block = ch_hdr + ch_payload + struct.pack("<H", ch_crc)

    body = bytearray(ch_block)
    for i, blk in enumerate(blocks):
        btype = blk.get("type", 1)
        if btype == 1:
            start_s = blk.get("start_sample", 0)
            raw_readings = blk.get("readings", [(100, 200)])
            payload = struct.pack("<HB", start_s, len(raw_readings))
            for r0, r1 in raw_readings:
                payload += struct.pack("<hh", r0, r1)
        else:
            samp = blk.get("sample", 0)
            sev = blk.get("severity", 0)
            msg = blk.get("message", "Event").encode("ascii")
            payload = struct.pack("<HBB", samp, sev, len(msg)) + msg

        b_hdr = struct.pack("<BBH", 0xB1, btype, len(payload))
        b_crc = crc16_ccitt(struct.pack("<BH", btype, len(payload)) + payload)
        if corrupt_block_crc_idx == i:
            b_crc ^= 0xBEEF
        body += b_hdr + payload + struct.pack("<H", b_crc)

    data = header + bytes(body)
    if truncate_bytes > 0:
        data = data[:-truncate_bytes]
    return bytes(data)


class TestLablogParser(unittest.TestCase):
    def setUp(self):
        self.parser = LablogParser()

    # --- Self-consistency tests ---

    def test_self_consistency_parse_valid_synthetic_lablog(self):
        """[self-consistency] Valid LABLOG file generated by calibrated helper."""
        blocks = [
            {"type": 1, "start_sample": 0, "readings": [(100, 200), (110, 210)]},
            {"type": 2, "sample": 1, "severity": 1, "message": "Notice"},
        ]
        data = build_synthetic_lablog(blocks)
        res = self.parser.parse("valid_log.lab", BoundedBinaryReader(data))

        self.assertTrue(res.is_valid_header)
        self.assertEqual(len(res.recovered_records), 2)
        self.assertEqual(len(res.damages), 0)
        self.assertEqual(res.recovered_records[0].fields["sample"], 0)
        self.assertEqual(res.recovered_records[0].status, RecordStatus.COMPLETE)

    def test_self_consistency_corrupted_block_checksum_isolation(self):
        """[self-consistency] Checksum isolation via synthetic helper."""
        blocks = [
            {"type": 1, "start_sample": 0, "readings": [(10, 20)]},
            {"type": 1, "start_sample": 1, "readings": [(30, 40)]},
        ]
        data = build_synthetic_lablog(blocks, corrupt_block_crc_idx=1)
        res = self.parser.parse("corrupt_blk.lab", BoundedBinaryReader(data))

        self.assertEqual(len(res.recovered_records), 2)
        self.assertEqual(res.recovered_records[0].status, RecordStatus.COMPLETE)
        self.assertEqual(res.recovered_records[1].status, RecordStatus.CORRUPTED)
        self.assertTrue(any(d.damage_type == DamageType.CHECKSUM_MISMATCH for d in res.damages))

    def test_self_consistency_truncated_block_recovery(self):
        """[self-consistency] Partial recovery on block payload truncation."""
        blocks = [
            {"type": 1, "start_sample": 0, "readings": [(10, 20)]},
            {"type": 1, "start_sample": 1, "readings": [(30, 40), (50, 60)]},
        ]
        data = build_synthetic_lablog(blocks, truncate_bytes=5)
        res = self.parser.parse("trunc.lab", BoundedBinaryReader(data))

        self.assertEqual(len(res.recovered_records), 1)
        self.assertEqual(res.recovered_records[0].status, RecordStatus.COMPLETE)
        self.assertTrue(any(d.damage_type == DamageType.TRUNCATION for d in res.damages))

    # --- Independent fixtures ---

    def test_independent_handcrafted_lablog_spec(self):
        """[independent] Hand-assembled LABLOG binary using calibrated LLOG byte definitions."""
        # 32B Header: 'LLOG', ver 1, num_ch 1, interval 10 (100 ms), instr 'TEST-LOG', start_sec 87628063, decl 2, res, crc
        instr_b = b"TEST-LOG".ljust(16, b"\x00")
        pre_hdr = struct.pack("<4sBBH16sIH", b"LLOG", 1, 1, 10, instr_b, 87628063, 2)
        hdr_crc = crc16_ccitt(pre_hdr)
        header = pre_hdr + struct.pack("<H", hdr_crc)

        # Channel block: 1 ch, unit 'mV', scale 1.0, offset 0.0
        ch_p = struct.pack("<4sff", b"mV\x00\x00", 1.0, 0.0)
        ch_crc = crc16_ccitt(struct.pack("<BH", 3, len(ch_p)) + ch_p)
        ch_blk = struct.pack("<BBH", 0xB1, 3, len(ch_p)) + ch_p + struct.pack("<H", ch_crc)

        # Data block: start 0, cnt 1, reading 42
        d_p = struct.pack("<HBh", 0, 1, 42)
        d_crc = crc16_ccitt(struct.pack("<BH", 1, len(d_p)) + d_p)
        d_blk = struct.pack("<BBH", 0xB1, 1, len(d_p)) + d_p + struct.pack("<H", d_crc)

        handcrafted = header + ch_blk + d_blk
        res = self.parser.parse("independent_log.lab", BoundedBinaryReader(handcrafted))

        self.assertTrue(res.is_valid_header)
        self.assertEqual(len(res.recovered_records), 1)
        self.assertEqual(res.recovered_records[0].fields["sample"], 0)
        self.assertEqual(res.recovered_records[0].fields["values"], [42.0])
        self.assertEqual(len(res.damages), 0)


if __name__ == "__main__":
    unittest.main()
