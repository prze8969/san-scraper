"""Tests for Lotus 1-2-3 Release 1A (.WKS) sequential record parser."""

import unittest
import struct
from src.formats.wks import WksParser
from src.reader import BoundedBinaryReader
from src.models import RecordStatus, DamageType

def build_synthetic_wks(
    records: list[tuple[int, bytes]],  # (opcode, payload)
    truncate_bytes: int = 0,
) -> bytes:
    """Helper to assemble a synthetic Lotus 1-2-3 .WKS file."""
    stream = bytearray()
    for opcode, payload in records:
        hdr = struct.pack("<HH", opcode, len(payload))
        stream += hdr + payload
    if truncate_bytes > 0:
        stream = stream[:-truncate_bytes]
    return bytes(stream)

class TestWksParser(unittest.TestCase):
    def setUp(self):
        self.parser = WksParser()

    # --- Self-consistency tests (generated via project's build_synthetic_wks helper) ---

    def test_self_consistency_minimal_valid_bof_eof_wks(self):
        """[self-consistency] Minimal BOF/EOF generated by internal helper."""
        bof_payload = struct.pack("<H", 0x0404)
        records = [
            (0x0000, bof_payload),
            (0x0001, b""),
        ]
        data = build_synthetic_wks(records)
        res = self.parser.parse("minimal.wks", BoundedBinaryReader(data))

        self.assertTrue(res.is_valid_header)
        self.assertEqual(len(res.recovered_records), 1)  # EOF record recorded
        self.assertTrue(res.metadata["saw_bof"])
        self.assertTrue(res.metadata["saw_eof"])
        self.assertEqual(res.metadata["version_code"], "0x0404")
        self.assertEqual(len(res.damages), 0)

    def test_self_consistency_canonical_cell_records(self):
        """[self-consistency] Canonical cell records via synthetic helper."""
        bof_payload = struct.pack("<H", 0x0404)
        blank_payload = struct.pack("<BHH", 0, 0, 0)
        int_payload = struct.pack("<BHHh", 0, 1, 2, 5432)
        num_payload = struct.pack("<BHHd", 0, 2, 2, 123.456)
        lbl_payload = struct.pack("<BHHB", 0, 3, 3, ord("'")) + b"QUAKE_TEST\x00"
        formula_payload = struct.pack("<BHHd", 0, 4, 4, 999.0)

        records = [
            (0x0000, bof_payload),
            (0x000C, blank_payload),
            (0x000D, int_payload),
            (0x000E, num_payload),
            (0x000F, lbl_payload),
            (0x0010, formula_payload),
            (0x0001, b""),  # EOF
        ]
        data = build_synthetic_wks(records)
        res = self.parser.parse("canonical_sheet.wks", BoundedBinaryReader(data))

        self.assertTrue(res.is_valid_header)
        self.assertEqual(len(res.recovered_records), 6)
        self.assertEqual(res.recovered_records[0].fields["record_type"], "BLANK")
        self.assertEqual(res.recovered_records[1].fields["value"], 5432)
        self.assertAlmostEqual(res.recovered_records[2].fields["value"], 123.456)
        self.assertEqual(res.recovered_records[3].fields["text"], "QUAKE_TEST")
        self.assertEqual(res.recovered_records[4].fields["record_type"], "FORMULA")

    def test_self_consistency_alternate_opcode_mapping_compatibility(self):
        """[self-consistency] Tests alternate mapping compatibility via helper."""
        bof_payload = struct.pack("<H", 0x0404)
        int_payload = struct.pack("<BHHh", 0, 1, 1, 100)
        records = [
            (0x0000, bof_payload),
            (0x000C, int_payload),
            (0x0001, b""),
        ]
        data = build_synthetic_wks(records)
        res = self.parser.parse("alt_mapping.wks", BoundedBinaryReader(data))
        self.assertEqual(res.recovered_records[0].fields["record_type"], "INTEGER")
        self.assertEqual(res.recovered_records[0].fields["value"], 100)

    def test_self_consistency_unknown_record_type_preserved(self):
        """[self-consistency] Preserving unknown opcodes safely."""
        bof_payload = struct.pack("<H", 0x0404)
        records = [
            (0x0000, bof_payload),
            (0x0099, b"\xAA\xBB\xCC\xDD"),
            (0x0001, b""),
        ]
        data = build_synthetic_wks(records)
        res = self.parser.parse("unknown_rec.wks", BoundedBinaryReader(data))
        self.assertEqual(len(res.recovered_records), 2)
        self.assertEqual(res.recovered_records[0].fields["record_type"], "UNKNOWN_OPCODE_0x0099")

    def test_self_consistency_missing_eof_and_truncated_record(self):
        """[self-consistency] Missing EOF and truncation detection."""
        bof_payload = struct.pack("<H", 0x0404)
        int_payload = struct.pack("<BHHh", 0, 1, 1, 42)
        records = [
            (0x0000, bof_payload),
            (0x000D, int_payload),
            (0x000D, int_payload),
        ]
        data = build_synthetic_wks(records, truncate_bytes=4)
        res = self.parser.parse("trunc.wks", BoundedBinaryReader(data))
        self.assertEqual(len(res.recovered_records), 1)
        self.assertTrue(any(d.damage_type == DamageType.TRUNCATION for d in res.damages))

    def test_self_consistency_unsupported_version_revision(self):
        """[self-consistency] Symphony version 0x0405 flags invalid header damage."""
        bof_payload = struct.pack("<H", 0x0405)
        records = [(0x0000, bof_payload), (0x0001, b"")]
        data = build_synthetic_wks(records)
        res = self.parser.parse("symphony.wrk", BoundedBinaryReader(data))
        self.assertTrue(any(d.damage_type == DamageType.INVALID_HEADER for d in res.damages))

    # --- Independent fixtures (hand-assembled byte strings from Lotus 1-2-3 specs, no writer used) ---

    def test_independent_handcrafted_lotus_wks_spec(self):
        """
        [independent] Hand-assembled Lotus 1-2-3 Release 1A file from byte specification.
        Source: Lotus Development Corp Worksheet File Format (WSFF1.TXT / WSFF2.TXT).
        Structure:
          1. BOF record: opcode 0x0000, length 2, version 0x0404
             bytes: 00 00 02 00 04 04
          2. INTEGER record: opcode 0x000D, length 7
             bytes: 0D 00 07 00 [format:00] [col:01 00] [row:02 00] [val: 2A 00] (val = 42)
          3. LABEL record: opcode 0x000F, length 11 (6 + 5)
             bytes: 0F 00 0B 00 [format:00] [col:00 00] [row:00 00] [align:27 (')] [text:b'WKS1\0']
          4. EOF record: opcode 0x0001, length 0
             bytes: 01 00 00 00
        """
        handcrafted = (
            b"\x00\x00\x02\x00\x04\x04"                               # BOF
            + b"\x0d\x00\x07\x00\x00\x01\x00\x02\x00\x2a\x00"        # INTEGER: col 1, row 2, val 42
            + b"\x0f\x00\x0b\x00\x00\x00\x00\x00\x00\x27WKS1\x00"     # LABEL: col 0, row 0, align "'", "WKS1"
            + b"\x01\x00\x00\x00"                                     # EOF
        )
        res = self.parser.parse("independent_spec.wks", BoundedBinaryReader(handcrafted))

        self.assertTrue(res.is_valid_header)
        self.assertEqual(len(res.recovered_records), 3)  # INTEGER, LABEL, EOF
        # Check INTEGER
        rec_int = res.recovered_records[0]
        self.assertEqual(rec_int.fields["record_type"], "INTEGER")
        self.assertEqual(rec_int.fields["col"], 1)
        self.assertEqual(rec_int.fields["row"], 2)
        self.assertEqual(rec_int.fields["value"], 42)

        # Check LABEL
        rec_lbl = res.recovered_records[1]
        self.assertEqual(rec_lbl.fields["record_type"], "LABEL")
        self.assertEqual(rec_lbl.fields["align_prefix"], "'")
        self.assertEqual(rec_lbl.fields["text"], "WKS1")

        # Check EOF
        rec_eof = res.recovered_records[2]
        self.assertEqual(rec_eof.fields["record_type"], "EOF")
        self.assertEqual(len(res.damages), 0)

    def test_independent_handcrafted_extended_precision_float(self):
        """
        [independent] Hand-crafted Lotus NUMBER cell with 10-byte 80-bit float.
        Source: x87 IEEE 754 80-bit extended precision float format.
        Value: 1.0 = sign: 0, exp: 16383 (0x3FFF), mantissa: 0x8000000000000000
        """
        # NUMBER opcode 0x000E, len 15 (1B fmt, 2B col, 2B row, 10B float)
        # fmt=0, col=5, row=10
        hdr = b"\x0e\x00\x0f\x00" # opcode 0x000E, len 15
        cell_addr = b"\x00\x05\x00\x0a\x00"
        float80 = struct.pack("<QH", 0x8000000000000000, 16383)
        bof = b"\x00\x00\x02\x00\x04\x04"
        eof = b"\x01\x00\x00\x00"
        handcrafted = bof + hdr + cell_addr + float80 + eof

        res = self.parser.parse("independent_float80.wks", BoundedBinaryReader(handcrafted))
        self.assertTrue(res.is_valid_header)
        self.assertEqual(len(res.recovered_records), 2)
        rec_num = res.recovered_records[0]
        self.assertEqual(rec_num.fields["record_type"], "NUMBER")
        self.assertEqual(rec_num.fields["col"], 5)
        self.assertEqual(rec_num.fields["row"], 10)
        self.assertAlmostEqual(rec_num.fields["value"], 1.0)

if __name__ == "__main__":
    unittest.main()
